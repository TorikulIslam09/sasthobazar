<?php
/**
 * UTF-8 / Bangla text health check (command line).
 *
 *   C:\xampp\php\php.exe database\check_utf8.php          report: connection, database, tables, columns, "????" rows, file encodings
 *   C:\xampp\php\php.exe database\check_utf8.php --sql    also write database/fix_utf8mb4.sql (ALTER statements for this database)
 *
 * Exit code 0 = everything is utf8mb4 and no "????" text was found, 1 = something needs attention.
 */
declare(strict_types=1);

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}
define('SKIP_INSTALL_CHECK', true);
require dirname(__DIR__) . '/core/bootstrap.php';

$pdo = Database::getInstance()->pdo();
$problems = 0;
$ok = static fn(bool $good, string $text) => print(($good ? '  OK   ' : '  FIX  ') . $text . "\n");

echo "1. Connection\n";
$c = $pdo->query('SELECT @@character_set_client a, @@character_set_connection b, @@character_set_results r, @@collation_connection col')->fetch(PDO::FETCH_ASSOC);
$good = $c['a'] === 'utf8mb4' && $c['b'] === 'utf8mb4' && $c['r'] === 'utf8mb4';
$problems += $good ? 0 : 1;
$ok($good, "client={$c['a']} connection={$c['b']} results={$c['r']} collation={$c['col']}");

echo "2. Database\n";
$db = $pdo->query('SELECT DATABASE() n, DEFAULT_CHARACTER_SET_NAME cs, DEFAULT_COLLATION_NAME col FROM information_schema.SCHEMATA WHERE SCHEMA_NAME = DATABASE()')->fetch(PDO::FETCH_ASSOC);
$good = $db['cs'] === 'utf8mb4';
$problems += $good ? 0 : 1;
$ok($good, "{$db['n']}: {$db['cs']} / {$db['col']}");

echo "3. Tables\n";
$tables = $pdo->query("SELECT TABLE_NAME, TABLE_COLLATION FROM information_schema.TABLES WHERE TABLE_SCHEMA = DATABASE() AND TABLE_TYPE = 'BASE TABLE' ORDER BY TABLE_NAME")->fetchAll(PDO::FETCH_KEY_PAIR);
$badTables = array_filter($tables, static fn($col) => !str_starts_with((string) $col, 'utf8mb4_'));
$problems += $badTables ? 1 : 0;
$ok(!$badTables, count($tables) . ' tables' . ($badTables ? ', not utf8mb4: ' . implode(', ', array_keys($badTables)) : ', all utf8mb4'));

echo "4. Text columns\n";
$cols = $pdo->query(
    "SELECT TABLE_NAME, COLUMN_NAME, COLUMN_TYPE, CHARACTER_SET_NAME, COLLATION_NAME, IS_NULLABLE, COLUMN_DEFAULT
       FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE() AND CHARACTER_SET_NAME IS NOT NULL ORDER BY TABLE_NAME, ORDINAL_POSITION"
)->fetchAll(PDO::FETCH_ASSOC);
$badCols = array_filter($cols, static fn($r) => $r['CHARACTER_SET_NAME'] !== 'utf8mb4');
$json = array_filter($cols, static fn($r) => $r['COLLATION_NAME'] === 'utf8mb4_bin');
$problems += $badCols ? 1 : 0;
$ok(!$badCols, count($cols) . ' columns' . ($badCols ? ', not utf8mb4: ' . implode(', ', array_map(static fn($r) => $r['TABLE_NAME'] . '.' . $r['COLUMN_NAME'] . ' (' . $r['CHARACTER_SET_NAME'] . ')', $badCols)) : ', all utf8mb4')
    . ' (' . count($json) . ' JSON columns use utf8mb4_bin on purpose)');

echo "5. Text already saved as \"????\" (cannot be shown correctly - restore or type again)\n";
$broken = 0;
foreach ($cols as $r) {
    if ($r['COLLATION_NAME'] === 'utf8mb4_bin' || in_array($r['TABLE_NAME'], ['audit_logs', 'message_logs', 'migrations', 'rate_limits'], true)) {
        continue;
    }
    $n = (int) $pdo->query("SELECT COUNT(*) FROM `{$r['TABLE_NAME']}` WHERE `{$r['COLUMN_NAME']}` LIKE '%???%'")->fetchColumn();
    if ($n) {
        $broken += $n;
        echo "  FIX  {$r['TABLE_NAME']}.{$r['COLUMN_NAME']}: {$n} row(s)\n";
    }
}
$problems += $broken ? 1 : 0;
if (!$broken) {
    echo "  OK   none\n";
} else {
    echo "       -> php database/repair_text.php restores seeded values (settings, roles, categories, pages ...)\n";
}

echo "6. Project files (UTF-8 without BOM)\n";
$files = 0;
$fileProblems = [];
$it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator(ROOT_PATH, FilesystemIterator::SKIP_DOTS));
foreach ($it as $f) {
    $p = str_replace('\\', '/', $f->getPathname());
    if (!preg_match('/\.(php|sql|js|css|html|htaccess|md|txt|ini)$/', $p) || preg_match('#/(storage|public/uploads)/#', $p)) {
        continue;
    }
    $files++;
    $s = (string) file_get_contents($p);
    if (str_starts_with($s, "\xEF\xBB\xBF")) {
        $fileProblems[] = 'BOM: ' . substr($p, strlen(ROOT_PATH) + 1);
    } elseif (!mb_check_encoding($s, 'UTF-8')) {
        $fileProblems[] = 'not UTF-8: ' . substr($p, strlen(ROOT_PATH) + 1);
    }
}
$problems += $fileProblems ? 1 : 0;
$ok(!$fileProblems, "{$files} files" . ($fileProblems ? ":\n         " . implode("\n         ", $fileProblems) : ', all UTF-8 without BOM'));

echo "7. Settings used by the site\n";
foreach (['site_name_bn', 'site_tagline', 'contact_address'] as $k) {
    $v = (string) setting($k, '');
    echo '       ' . str_pad($k, 16) . $v . "\n";
}

if (in_array('--sql', $argv, true)) {
    $out = "-- SasthoBazar: convert the database, every table and every text column to utf8mb4 / utf8mb4_unicode_ci.\n"
        . "-- Generated by database/check_utf8.php on " . date('Y-m-d H:i') . " for this schema. Safe to run more than once.\n"
        . "-- phpMyAdmin: select the database on the left, open the SQL tab, paste this file, Go.\n"
        . "-- CLI: mysql --default-character-set=utf8mb4 -u root -p DBNAME < database/fix_utf8mb4.sql\n"
        . "-- This does NOT bring back text that is already stored as \"????\" - see database/repair_text.php.\n\n"
        . "SET NAMES utf8mb4;\nSET FOREIGN_KEY_CHECKS = 0;\n\n"
        . "ALTER DATABASE CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;\n\n";
    foreach (array_keys($tables) as $t) {
        $out .= "ALTER TABLE `{$t}` CONVERT TO CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;\n";
    }
    $out .= "\n-- JSON columns: MariaDB / MySQL keep JSON as utf8mb4_bin - put them back after the conversion above.\n";
    foreach ($json as $r) {
        $null = $r['IS_NULLABLE'] === 'YES' ? 'NULL' : 'NOT NULL';
        $out .= "ALTER TABLE `{$r['TABLE_NAME']}` MODIFY `{$r['COLUMN_NAME']}` {$r['COLUMN_TYPE']} CHARACTER SET utf8mb4 COLLATE utf8mb4_bin {$null};\n";
    }
    $out .= "\nSET FOREIGN_KEY_CHECKS = 1;\n";
    file_put_contents(ROOT_PATH . '/database/fix_utf8mb4.sql', $out);
    echo "\nWrote database/fix_utf8mb4.sql (" . count($tables) . " tables, " . count($json) . " JSON columns)\n";
}

echo "\n" . ($problems ? "{$problems} problem(s) found.\n" : "Everything is UTF-8 (utf8mb4).\n");
exit($problems ? 1 : 0);
